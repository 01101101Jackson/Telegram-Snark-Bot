export type LanguageCode = keyof typeof languages;

export function getMessage(langCode: LanguageCode, key: keyof typeof languages.en.messages, replacements?: Record<string, string>): string {
  let message = languages[langCode]?.messages[key] || languages.en.messages[key];

  if (replacements) {
    Object.entries(replacements).forEach(([key, value]) => {
      message = message.replace(`{${key}}`, value);
    });
  }

  return message;
}

export function getLanguagePrompt(langCode: LanguageCode): string {
  return languages[langCode]?.prompts.language || languages.en.prompts.language;
}
